def parse_game(text):
    moves = []
    for line in text.strip().split('\n'):
        if 'moves' in line:
            parts = line.split('moves ')[1]
            f_str, t_str = parts.split(' -> ')
            f = eval(f_str)
            t = eval(t_str)
            moves.append({"from": [f[0], f[1]], "to": [t[0], t[1]]})
    return moves

